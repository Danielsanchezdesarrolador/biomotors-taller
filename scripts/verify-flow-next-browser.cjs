const {chromium}=require('playwright')
const assert=require('node:assert/strict')
const fs=require('node:fs')
;(async()=>{
 const out=process.env.OUTPUT_DIR||'docs/screenshots/bt-flow-next-01'
 fs.mkdirSync(out,{recursive:true})
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox']})
 try{
  for(const width of [1366,390]){
   const page=await browser.newPage({viewport:{width,height:900}})
   page.on('dialog',d=>d.accept())
   await page.goto('http://127.0.0.1:47130/guided-qa?stage=4')
   await page.getByRole('button',{name:/Continuar$/}).last().click()
   await page.getByRole('button',{name:'Continuar atención',exact:true}).click()
   await page.getByRole('heading',{name:'5. Aprobación del cliente',exact:true}).waitFor()
   await page.getByRole('button',{name:'Confirmar e iniciar trabajos',exact:true}).click()
   await page.getByText('Selecciona un medio de aprobación.',{exact:true}).waitFor()
   assert.equal(await page.evaluate(()=>window.r1.writes),0)
   await page.getByLabel('Medio de aprobación',{exact:true}).selectOption('phone')
   await page.getByLabel(/Observaciones de la autorización/).fill('Cliente ficticio autoriza revisión vigente por teléfono.')
   await page.getByRole('checkbox',{name:/Declaro que verifiqué/}).check()
   await page.getByRole('button',{name:'Confirmar e iniciar trabajos',exact:true}).click()
   await page.getByRole('heading',{name:'6. Ejecución de trabajos',exact:true}).waitFor()
   assert.equal(await page.evaluate(()=>window.r1.writes),1)
   await page.screenshot({path:out+'/ejecucion-'+width+'.png',fullPage:true})
   await page.getByRole('button',{name:'Ver avance de atención'}).click()
   await page.screenshot({path:out+'/avance-'+width+'.png',fullPage:true})
   assert(await page.getByRole('button',{name:'Continuar atención',exact:true}).isVisible())
   assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1))
   console.log('PASS approval guard, confirmed navigation, dashboard, responsive',width)
   await page.reload()
   await page.getByRole('button',{name:/Continuar$/}).last().click()
   await page.getByRole('button',{name:'Abrir inspección multipunto',exact:true}).click()
   await page.getByRole('heading',{name:/Inspección multipunto con X/}).waitFor()
   await page.screenshot({path:out+'/inspeccion-'+width+'.png',fullPage:true})
   await page.getByRole('button',{name:'Finalizar inspección y preparar cotización',exact:true}).click()
   await page.getByRole('heading',{name:'5. Aprobación del cliente',exact:true}).waitFor()
   console.log('PASS complete technical inspection, existing quote reused',width)
   await page.goto('http://127.0.0.1:47130/guided-qa?stage=4&failure=denied')
   await page.getByRole('button',{name:/Continuar$/}).last().click()
   await page.getByRole('button',{name:'Continuar atención',exact:true}).click()
   await page.getByLabel('Medio de aprobación',{exact:true}).selectOption('phone')
   const note='Conservar observación ficticia tras rechazo del servidor.'
   await page.getByLabel(/Observaciones de la autorización/).fill(note)
   await page.getByRole('checkbox',{name:/Declaro que verifiqué/}).check()
   await page.getByRole('button',{name:'Confirmar e iniciar trabajos',exact:true}).click()
   await page.getByRole('alert').waitFor()
   assert.equal(await page.getByLabel(/Observaciones de la autorización/).inputValue(),note)
   assert(await page.getByRole('heading',{name:'5. Aprobación del cliente',exact:true}).isVisible())
   console.log('PASS denied save preserves fields and stage',width)
   await page.goto('http://127.0.0.1:47130/guided-qa?stage=7&failure=archive-pending')
   await page.getByRole('button',{name:/Continuar$/}).last().click()
   await page.getByRole('button',{name:'Continuar atención',exact:true}).click()
   await page.getByRole('heading',{name:'8. Expediente final',exact:true}).waitFor()
   await page.getByRole('button',{name:'Cerrar atención',exact:true}).click()
   await page.waitForFunction(()=>window.r1.archives===1)
   await page.getByRole('button',{name:'Cerrar atención',exact:true}).click()
   assert.equal(await page.evaluate(()=>window.r1.archives),1)
   console.log('PASS final archive confirmation reconciled without duplicate',width)
   await page.close()
  }
 }finally{await browser.close()}
})().catch(error=>{console.error(error);process.exitCode=1})