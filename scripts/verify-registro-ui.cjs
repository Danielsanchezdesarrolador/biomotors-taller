// BT-REG-02: capturas/e2e Chromium de desarrollo. Sin pruebas Auth A/B ni backend.
const { chromium }=require('playwright')
const fs=require('node:fs')
const assert=require('node:assert/strict')
const path=require('node:path')
const out=path.join(process.cwd(),'artifacts','bt-reg-02')
fs.mkdirSync(out,{recursive:true})

;(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']})
 const report=[]
 try{
  for(const width of [1650,390]){
   const page=await browser.newPage({viewport:{width,height:900},deviceScaleFactor:1})
   const errors=[],writes=[]
   page.on('pageerror',e=>errors.push(e.message))
   page.on('request',r=>{if(!['GET','HEAD'].includes(r.method()))writes.push({method:r.method(),url:r.url()})})
   await page.goto('http://127.0.0.1:5177/',{waitUntil:'networkidle'})
   const nav=page.locator(width>760?'.side-nav button':'.bottom-nav button')
   assert.equal(await nav.count(),5)
   await nav.nth(2).click()
   await page.getByRole('heading',{name:'Clientes y vehículos',exact:true}).waitFor()
   assert.equal(await page.locator('.cv-intake-item').count(),2)
   assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
   await page.getByRole('button',{name:'Generar enlace de registro',exact:true}).click()
   const modal=page.getByRole('dialog')
   assert.equal(await modal.locator('a').count(),0)
   await modal.getByRole('button',{name:'Abrir formulario público DEMO'}).click()
   await modal.getByRole('heading',{name:'Cuéntanos quién eres'}).waitFor()
   await page.screenshot({path:path.join(out,'BT_REG_02_'+width+'_FORM.png')})
   await modal.getByLabel('Nombre completo *',{exact:true}).fill('Cliente de prueba')
   await modal.getByLabel('Correo electrónico *',{exact:true}).fill('cliente@example.com')
   await modal.getByLabel('Teléfono *',{exact:true}).fill('+56 9 0000 0000')
   await modal.getByRole('checkbox').check()
   await modal.getByRole('button',{name:'Continuar'}).click()
   await modal.getByLabel('Marca *',{exact:true}).fill('Toyota')
   await modal.getByLabel('Modelo *',{exact:true}).fill('Corolla')
   await modal.getByLabel('Año *',{exact:true}).fill('2020')
   await modal.getByLabel('Kilometraje actual *',{exact:true}).fill('68430')
   await modal.getByRole('button',{name:'Continuar'}).click()
   await modal.getByRole('button',{name:'Escucho un ruido al pasar por baches.'}).click()
   await modal.getByRole('button',{name:'Revisar datos'}).click()
   await modal.getByRole('heading',{name:'Revisa tus antecedentes'}).waitFor()
   await page.screenshot({path:path.join(out,'BT_REG_02_'+width+'_RESUMEN.png')})
   await modal.getByRole('button',{name:'Finalizar simulación'}).click()
   await modal.getByText('Simulación completada. No se enviaron ni almacenaron datos reales.').waitFor()
   await page.keyboard.press('Escape')
   await page.locator('.cv-intake-item').nth(2).waitFor()
   assert.equal(await page.locator('.cv-intake-item').count(),3)
   assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
   await page.screenshot({path:path.join(out,'BT_REG_02_'+width+'_SOLICITUDES.png'),fullPage:true})
   assert.deepEqual(writes,[])
   assert.equal(await page.evaluate(()=>localStorage.length+sessionStorage.length),0)
   await page.reload()
   await nav.nth(2).click()
   assert.equal(await page.locator('.cv-intake-item').count(),2)
   assert.deepEqual(errors,[])
   report.push({width,steps:3,requests_after_submit:3,requests_after_reload:2,network_writes:0,storage_items:0,errors})
   await page.close()
  }
 }finally{await browser.close()}
 fs.writeFileSync(path.join(out,'BT_REG_02_RESULTADOS.json'),JSON.stringify(report,null,2)+'\n')
 console.log('BT-REG-02 E2E PASS:',JSON.stringify(report))
})().catch(error=>{console.error(error);process.exitCode=1})
