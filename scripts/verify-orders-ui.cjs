// Browser acceptance checks. Uses Playwright supplied by the cloud runtime.
// Start `npm run dev -- --port 5177 --strictPort` before executing this script.
const { chromium } = require('playwright')
const assert = require('node:assert/strict')
async function openSample(page) {
  const desktop=page.getByRole('button',{name:'Abrir OT-1002',exact:true})
  if(await desktop.isVisible()) await desktop.click()
  else await page.locator('.bt-ot-mobile-order').filter({hasText:'OT-1002'}).click()
  await page.getByRole('heading',{name:'Orden de trabajo',exact:true}).waitFor()
}
;(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',args:['--no-sandbox']})
 try {
  for(const width of [1650,1440,768,390,375]) {
   const page=await browser.newPage({viewport:{width,height:941}}),errors=[]
   page.on('pageerror',error=>errors.push(error.message))
   await page.goto(process.env.BASE_URL||'http://127.0.0.1:5177')
   await page.locator(width>760?'.side-nav button':'.bottom-nav button').nth(1).click()
   await openSample(page)
   assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,`overflow at ${width}`)
   assert.match(await page.getByTestId('order-total').innerText(),/154.879/)
   assert.equal(await page.locator('.od-count').first().innerText(),'6 de 8 ítems')
   await page.getByLabel('Niveles de fluidos (refrigerante, frenos, etc.)',{exact:true}).selectOption('correcto')
   assert.equal(await page.locator('.od-count').first().innerText(),'7 de 8 ítems')
   await page.getByRole('button',{name:'Continuar orden',exact:true}).click()
   assert.equal(await page.locator('.od-inspection').evaluate(e=>e===document.activeElement),true)
   await page.getByRole('button',{name:'Agregar ítem',exact:true}).click()
   await page.getByLabel('Descripción',{exact:true}).fill('Repuesto de prueba')
   await page.getByLabel('Cantidad',{exact:true}).fill('2')
   await page.getByLabel('Precio unitario (CLP)',{exact:true}).fill('1000')
   await page.getByRole('button',{name:'Agregar a la DEMO',exact:true}).click()
   assert.match(await page.getByTestId('order-total').innerText(),/157.259/)
   await page.getByRole('button',{name:'Generar informe',exact:true}).click()
   const report=page.getByRole('dialog')
   assert.match(await report.innerText(),/157.259/)
   assert.match(await report.innerText(),/7 de 8/)
   await page.keyboard.press('Escape')
   assert.equal(await page.locator('dialog').count(),0)
   await page.evaluate(()=>{window.__printed=false;window.print=()=>window.__printed=true})
   await page.getByRole('button',{name:'Imprimir',exact:true}).click()
   assert.equal(await page.evaluate(()=>window.__printed),true)
   await page.getByLabel('Estado de orden DEMO',{exact:true}).selectOption('repuestos')
   assert.match(await page.locator('.od-progress li.current').innerText(),/Por repuestos/)
   await page.getByRole('button',{name:'Finalizar',exact:true}).click()
   await page.getByRole('button',{name:'Cerrar / cancelar',exact:true}).click()
   assert.equal(await page.getByLabel('Estado de orden DEMO').inputValue(),'repuestos')
   await page.getByRole('button',{name:'Finalizar',exact:true}).click()
   await page.getByRole('button',{name:'Confirmar finalización DEMO',exact:true}).click()
   assert.equal(await page.getByLabel('Estado de orden DEMO').inputValue(),'finalizada')
   assert.equal(await page.locator('.od-progress li.done').count(),4)
   assert.equal(await page.locator('.od-pending li').count(),3)
   await page.getByRole('button',{name:'Volver al listado de órdenes',exact:true}).click()
   await openSample(page)
   // UI-05 keeps the revision in page memory for report preparation; reload still resets it.
   assert.match(await page.getByTestId('order-total').innerText(),/157.259/)
   await page.reload()
   await page.locator(width>760?'.side-nav button':'.bottom-nav button').nth(1).click()
   await openSample(page)
   assert.equal(await page.getByLabel('Estado de orden DEMO').inputValue(),'servicio')
   assert.deepEqual(errors,[])
   console.log(`${width}px: PASS — navigation, overflow, inspection, items, totals, preview, print invocation, cancel, finalize, progress and reset`)
   await page.close()
  }
 } finally { await browser.close() }
})().catch(error=>{console.error(error);process.exitCode=1})
